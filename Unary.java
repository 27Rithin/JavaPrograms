class Unary
{
    public static void main(String args[])
    {
        int a = 2;
        boolean flag = true;

        //increment operator
        System.out.println(++a);
        System.out.println(a++);

        //decrement operator
        System.out.println(--a);
        System.out.println(a--);

        //logial NOT operator
        System.out.println(!flag);

        //unary plus operator
        System.out.println(+a);
        
        //unary minus operator
        System.out.println(-a);
    }
}