class Logical
{
    public static void main(String args[])
    {
        int a = 4;
        int b = 7;
        //AND operator 
        System.out.println(a<3 && a!=b);
        System.out.println(a>3 && a!=b);
        //OR operator
        System.out.println(a<3 || a!=b);
        System.out.println(a>3 || a!=b);
    }
}